from PIL import Image, ImageDraw, PngImagePlugin
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parent
im=Image.new("RGBA",(1024,1024),(0,0,0,0))
draw=ImageDraw.Draw(im);draw.rounded_rectangle((224,224,800,800),radius=100,fill=(40,130,210,255))
meta=PngImagePlugin.PngInfo();meta.add_text("Description","SYNTHETIC CPU TEST FIXTURE; NOT GENERATED BY A MODEL")
p=root/"sources"/"synthetic-not-generated.png";im.save(p,pnginfo=meta)
(root/"sources"/"SYNTHETIC-NOT-GENERATED.txt").write_text("CPU Pillow geometry only. No model or inference. Not eligible as existing ComfyUI generation provenance.",encoding="utf8")
print(json.dumps({"sourcePath":str(p),"sha256":hashlib.sha256(p.read_bytes()).hexdigest(),"size":im.size,"mode":im.mode}))
